-- PRODUCTS
CREATE TABLE products (
    product_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR2(100) NOT NULL,
    price        NUMBER(10,2) NOT NULL,
    qty_on_hand  NUMBER DEFAULT 0,
    reorder_point NUMBER DEFAULT 5
);

-- SUPPLIERS
CREATE TABLE suppliers (
    supplier_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR2(100) NOT NULL,
    phone        VARCHAR2(20)
);

-- CUSTOMERS
CREATE TABLE customers (
    customer_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR2(100) NOT NULL,
    phone        VARCHAR2(20)
);

-- EMPLOYEES
CREATE TABLE employees (
    employee_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR2(100) NOT NULL,
    position     VARCHAR2(50),
    hire_date    DATE DEFAULT SYSDATE
);

-- PURCHASES (nhập hàng)
CREATE TABLE purchases (
    purchase_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id  NUMBER,
    employee_id  NUMBER,
    purchase_date DATE DEFAULT SYSDATE,
    total_amount NUMBER(10,2),
    CONSTRAINT fk_purchase_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
    CONSTRAINT fk_purchase_emp FOREIGN KEY (employee_id) REFERENCES employees(employee_id)
);

-- PURCHASE_ITEMS
CREATE TABLE purchase_items (
    purchase_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id  NUMBER,
    product_id   NUMBER,
    qty          NUMBER,
    unit_cost    NUMBER(10,2),
    line_total   NUMBER(10,2),
    CONSTRAINT fk_pi_purchase FOREIGN KEY (purchase_id) REFERENCES purchases(purchase_id),
    CONSTRAINT fk_pi_product FOREIGN KEY (product_id) REFERENCES products(product_id)
);

-- SALES (bán hàng)
CREATE TABLE sales (
    sale_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  NUMBER,
    employee_id  NUMBER,
    sale_date    DATE DEFAULT SYSDATE,
    total_amount NUMBER(10,2),
    CONSTRAINT fk_sale_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT fk_sale_emp FOREIGN KEY (employee_id) REFERENCES employees(employee_id)
);

-- SALE_ITEMS
CREATE TABLE sale_items (
    sale_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id      NUMBER,
    product_id   NUMBER,
    qty          NUMBER,
    unit_price   NUMBER(10,2),
    line_total   NUMBER(10,2),
    CONSTRAINT fk_si_sale FOREIGN KEY (sale_id) REFERENCES sales(sale_id),
    CONSTRAINT fk_si_product FOREIGN KEY (product_id) REFERENCES products(product_id)
);
SET SERVEROUTPUT ON;

-- Khi nhập hàng thì cộng tồn kho
CREATE OR REPLACE TRIGGER trg_purchase_item_ai
AFTER INSERT ON purchase_items
FOR EACH ROW
BEGIN
    UPDATE products
    SET qty_on_hand = qty_on_hand + :NEW.qty
    WHERE product_id = :NEW.product_id;
END;
/

-- Khi bán hàng thì trừ tồn kho
CREATE OR REPLACE TRIGGER trg_sale_item_ai
AFTER INSERT ON sale_items
FOR EACH ROW
DECLARE
    v_stock NUMBER;  -- biến tạm để lưu tồn kho
BEGIN
    -- Lấy số lượng tồn hiện tại
    SELECT qty_on_hand 
    INTO v_stock
    FROM products 
    WHERE product_id = :NEW.product_id;

    -- So sánh
    IF :NEW.qty > v_stock THEN
        RAISE_APPLICATION_ERROR(-20001, 'Không đủ hàng trong kho');
    ELSE
        UPDATE products
        SET qty_on_hand = qty_on_hand - :NEW.qty
        WHERE product_id = :NEW.product_id;
    END IF;
END;
/

-- kiểm tra hàng tồn kho và bán
DECLARE
    v_stock NUMBER;
    v_qty   NUMBER := &SoLuongMua;   -- nhập khi chạy
    v_pid   NUMBER := &ProductID;    -- nhập Product ID khi chạy
    v_cid   NUMBER := &CustomerID;   -- nhập Customer ID khi chạy
    v_eid   NUMBER := &EmployeeID;   -- nhập Employee ID khi chạy
    v_saleid NUMBER;                 -- ID của hóa đơn bán hàng
BEGIN
    -- 1. Lấy số lượng tồn kho hiện tại
    SELECT qty_on_hand INTO v_stock
    FROM Products
    WHERE product_id = v_pid;

    -- 2. Kiểm tra tồn kho
    IF v_stock >= v_qty THEN
        -- 3. Tạo hóa đơn bán hàng (Sales)
        INSERT INTO Sales (customer_id, employee_id)
        VALUES (v_cid, v_eid)
        RETURNING sale_id INTO v_saleid;

        -- 4. Thêm chi tiết hóa đơn (Sale_Items)
        INSERT INTO Sale_Items (sale_id, product_id, qty, unit_price)
        VALUES (v_saleid, v_pid, v_qty,
                (SELECT price FROM Products WHERE product_id = v_pid));

        -- 5. Cập nhật tồn kho
        UPDATE Products
        SET qty_on_hand = qty_on_hand - v_qty
        WHERE product_id = v_pid;

        DBMS_OUTPUT.PUT_LINE('Success: Customer ' || v_cid ||
                             ' bought ' || v_qty || ' of product ' || v_pid ||
                             '. Remaining stock = ' || (v_stock - v_qty));
    ELSE
        DBMS_OUTPUT.PUT_LINE('Error: Not enough stock. Current stock = ' || v_stock);
    END IF;
END;
/
-- nhập hàng
DECLARE
    v_pid   NUMBER := &ProductID;     -- nhập ID sản phẩm
    v_sid   NUMBER := &SupplierID;    -- nhập ID nhà cung cấp
    v_eid   NUMBER := &EmployeeID;    -- nhập ID nhân viên
    v_qty   NUMBER := &SoLuongNhap;   -- nhập số lượng nhập
    v_price NUMBER := &GiaNhap;       -- nhập giá nhập
    v_stock NUMBER;
    v_purid NUMBER;                   -- ID của hóa đơn nhập
BEGIN
    -- 1. Tạo hóa đơn nhập (Purchases)
    INSERT INTO Purchases (supplier_id, employee_id)
    VALUES (v_sid, v_eid)
    RETURNING purchase_id INTO v_purid;

    -- 2. Thêm chi tiết nhập hàng (Purchase_Items)
    INSERT INTO Purchase_Items (purchase_id, product_id, qty, unit_price)
    VALUES (v_purid, v_pid, v_qty, v_price);

    -- 3. Cập nhật tồn kho trong Products
    UPDATE Products
    SET qty_on_hand = qty_on_hand + v_qty
    WHERE product_id = v_pid
    RETURNING qty_on_hand INTO v_stock;

    -- 4. In thông báo kết quả
    DBMS_OUTPUT.PUT_LINE(' Nhập hàng thành công! ProductID = ' || v_pid ||
                         ', Số lượng nhập = ' || v_qty ||
                         ', Tồn kho mới = ' || v_stock);
END;
/

-- hiển thị đơn hàng mà khách đã mua 
SELECT s.sale_id,
       c.name      AS customer_name,
       p.name      AS product_name,
       si.qty,
       si.unit_price,
       (si.qty * si.unit_price) AS total_amount,
       s.sale_date
FROM Sales s
JOIN Customers c ON s.customer_id = c.customer_id
JOIN Sale_Items si ON s.sale_id = si.sale_id
JOIN Products p ON si.product_id = p.product_id
ORDER BY s.sale_id;

-- kiểm tra doanh thu theo từng nhân viên 
SELECT e.employee_id, e.name AS employee_name,
       SUM(si.qty * si.unit_price) AS total_revenue
FROM Employees e
JOIN Sales s ON e.employee_id = s.employee_id
JOIN Sale_Items si ON s.sale_id = si.sale_id
GROUP BY e.employee_id, e.name
ORDER BY total_revenue DESC;

-- hiển thị sản phẩm bán chạy nhất
SELECT p.product_id, p.name AS product_name,
       SUM(si.qty) AS total_sold
FROM Products p
JOIN Sale_Items si ON p.product_id = si.product_id
GROUP BY p.product_id, p.name
ORDER BY total_sold DESC;

